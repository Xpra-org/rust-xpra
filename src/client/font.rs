// Draw `text` into `fb` (a `fb_width`-wide 0x00RRGGBB framebuffer) at top-left (x, y), each glyph
// scaled by `scale`, in `color`. Non-printable/out-of-range bytes render as blank cells. Pixels
// outside the framebuffer are clipped.
pub fn blit_str(fb: &mut [u32], fb_width: usize, x: i32, y: i32, scale: i32, text: &str, color: u32) {
    let fb_height = (fb.len() / fb_width.max(1)) as i32;
    let mut cx = x;
    for ch in text.bytes() {
        let glyph = if (0x20..=0x7E).contains(&ch) {
            &FONT[(ch - 0x20) as usize]
        } else {
            &FONT[0] // space
        };
        for (row, bits) in glyph.iter().enumerate() {
            for col in 0..GLYPH_W {
                if bits & (1 << col) == 0 {
                    continue;
                }
                // scale each font pixel into a scale x scale block:
                for dy in 0..scale {
                    for dx in 0..scale {
                        let px = cx + col * scale + dx;
                        let py = y + row as i32 * scale + dy;
                        if px >= 0 && px < fb_width as i32 && py >= 0 && py < fb_height {
                            fb[py as usize * fb_width + px as usize] = color;
                        }
                    }
                }
            }
        }
        cx += GLYPH_W * scale; // advance one cell (glyphs include their own spacing)
    }
}

// The width of `text` when drawn at `scale`, in pixels.
pub fn text_width(text: &str, scale: i32) -> i32 {
    text.chars().count() as i32 * GLYPH_W * scale
}
